#!/usr/bin/env bash
# Build a single static ARMv7 hard-float dropbearmulti (dropbear, dropbearkey,
# dbclient, scp) for the Prusa/Buddy3D camera. See env.sh for the toolchain.
set -euo pipefail

source "$(dirname "$0")/env.sh"
toolchain_init "$@"

# The musl toolchain defaults to PIE; -static would then yield static-pie,
# which is not acceptable. Force a plain static non-PIE executable.
export CFLAGS="$CFLAGS -fno-pie"
export LDFLAGS="$LDFLAGS -no-pie"

PKG=dropbear
VER=2026.94
URL="https://matt.ucc.asn.au/dropbear/releases/dropbear-${VER}.tar.bz2"
SHA256=e098034a843699200c8c977a991fff73159735bf795d5f72ef672c41a6b1ae81

# Device PATH for non-interactive ssh sessions. Root (the only login on the
# camera) gets DEFAULT_ROOT_PATH, so both macros are overridden.
DEVICE_PATH="/userdata/bin:/oem/bin:/usr/bin:/bin:/usr/sbin:/sbin"

TARBALL="$(fetch "$URL" "$SHA256")"

SRC="$BUILD/${PKG}-${VER}"
rm -rf "$SRC"
tar -xjf "$TARBALL" -C "$BUILD"
cd "$SRC"

# Local compile-time options (picked up via LOCALOPTIONS_H_EXISTS in the
# top-level Makefile). Password logins are compiled out; no secrets involved.
cat > localoptions.h <<EOF
/* Generated by build-dropbear.sh */
#undef DEFAULT_PATH
#define DEFAULT_PATH "${DEVICE_PATH}"
#undef DEFAULT_ROOT_PATH
#define DEFAULT_ROOT_PATH "${DEVICE_PATH}"
#undef DROPBEAR_SVR_PASSWORD_AUTH
#define DROPBEAR_SVR_PASSWORD_AUTH 0
/* Non-PIE static binary: re-exec exists only for ASLR, so it buys nothing here.
   It also needs execveat(AT_EMPTY_PATH), which qemu-user lacks (smoke tests). */
#undef DROPBEAR_REEXEC
#define DROPBEAR_REEXEC 0
EOF

./configure \
  --host="$CROSS_TRIPLE" \
  --enable-static \
  --enable-bundled-libtom \
  --disable-zlib \
  --disable-pam \
  --disable-shadow \
  --disable-syslog \
  --disable-lastlog \
  --disable-utmp \
  --disable-utmpx \
  --disable-wtmp \
  --disable-wtmpx \
  --disable-loginfunc \
  --disable-pututxline

make PROGRAMS="dropbear dropbearkey dbclient scp" MULTI=1 -j"$(nproc)"

"${STRIP}" -s -o "$OUT/dropbearmulti" dropbearmulti
chmod 0755 "$OUT/dropbearmulti"

echo "package:        ${PKG} ${VER}"
echo "tarball:        ${URL}"
echo "tarball sha256: ${SHA256}"
echo "device PATH:    ${DEVICE_PATH}"
echo "output:         ${OUT}/dropbearmulti"
echo "output sha256:  $(sha256sum "$OUT/dropbearmulti" | cut -d' ' -f1)"
echo "output size:    $(stat -c %s "$OUT/dropbearmulti") bytes"
